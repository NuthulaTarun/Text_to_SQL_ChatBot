def get_nlp_response_chain(db=get_database()):
    llm = get_claude_llm()

    with open("src/prompts/nlresponse_prompt.txt") as f:
        template = f.read()

    prompt = ChatPromptTemplate.from_template(template)

    nlp_response_schema = ResponseSchema(
        name="nlp_output",
        description="This is the natural language response generated by the LLM based on the Conversation History, SQL Query, User question and SQL response. DO NOT include any links here in the response.",
    )

    nlp_output_parser = StructuredOutputParser(response_schemas=[nlp_response_schema])

    nlp_output_generation_chain = RunnablePassthrough.assign(
        response=lambda vars: db.run(vars["query"])
    ).assign(output=prompt | llm | nlp_output_parser)

    return nlp_output_generation_chain, nlp_output_parser


