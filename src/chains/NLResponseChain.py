# Parallel execution of nlp response chain and plot columns chain
def get_nlp_response_and_plot_columns(
    user_query, sql_query, chat_history, sql_response, db=get_database()
):

    nlp_output_generation_chain, nlp_output_parser = get_nlp_response_chain(db=db)
    (
        plot_columns_chain,
        plot_columns_format_instructions,
        plot_columns_output_parser,
    ) = get_plot_columns_chain(user_query, sql_response)

    parallel_chain = RunnableParallel(
        nlp_response_chain=nlp_output_generation_chain,
        plot_columns_response_chain=plot_columns_chain,
    )

    parallel_chain_response = parallel_chain.invoke(
        {
            "input": user_query,
            "chat_history": chat_history,
            "query": sql_query,
            "nlp_format_instructions": nlp_output_parser.get_format_instructions(),
            "sql_response": sql_response,
            "plot_columns_format_instructions": plot_columns_format_instructions,
        }
    )

    # getting nlp response
    nlp_output = parallel_chain_response["nlp_response_chain"]["output"]
    result = {}
    result["nlp_output"] = nlp_output["nlp_output"]

    if len(sql_response) > 1:
        result["sql_response"] = sql_response
    else:
        result["sql_response"] = "N/A"
    print(f"Final response: \n\n {result}\n\n")

    # getting plot columns
    plot_columns = plot_columns_output_parser.parse(
        parallel_chain_response["plot_columns_response_chain"][
            "plot_columns_query"
        ].content
    )["plot_columns"]
    print(f"columns that can be used for plotting is {plot_columns}")
    if isinstance(plot_columns, str):
        plot_columns = plot_columns.split(",")
    plot_columns = [item.strip() for item in plot_columns]

    result["plot_columns"] = plot_columns
    return result, sql_query


def get_nlp_response_gen_exception(e):
    print(f"exception at getting nlp response {e}")
    sql_query = f"exception at getting nlp response {e}"
    result = {}
    result["nlp_output"] = FAILURE_RESPONSE
    result["sql_response"] = "N/A"
    return result, sql_query


